#!/usr/bin/env node
// Local caching npm mirror (verdaccio) used by the benchmarks.
//
//   node bench/mirror.ts start     start verdaccio on 127.0.0.1:4873 (no-op if already up)
//   node bench/mirror.ts stop      stop it
//   node bench/mirror.ts status    print whether it answers
//   node bench/mirror.ts prewarm   install every fixture once with npm through the mirror
//
// Uplink is registry.npmjs.org through the proxy from the environment (HTTPS_PROXY etc.).
// Metadata is cached for 30 days so timed runs never wait on the uplink.
import { spawn } from "node:child_process";
import { closeSync, cpSync, existsSync, openSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  DEFAULT_REGISTRY,
  FIXTURES_DIR,
  TMP_DIR,
  ensureDir,
  isMain,
  log,
  registryAlive,
  registryUrl,
  rmrf,
  runOk,
  sleep,
  which,
} from "./lib/util.ts";

export const VERDACCIO_VERSION = "6.11.1";
const MIRROR_DIR = join(TMP_DIR, "verdaccio");
const PID_FILE = join(MIRROR_DIR, "verdaccio.pid");
const LOG_FILE = join(MIRROR_DIR, "verdaccio.log");
const CONFIG_FILE = join(MIRROR_DIR, "config.yaml");

function env(name: string): string | undefined {
  return process.env[name] || process.env[name.toLowerCase()] || undefined;
}

function writeConfig(): void {
  ensureDir(join(MIRROR_DIR, "storage"));
  const httpsProxy = env("HTTPS_PROXY");
  const httpProxy = env("HTTP_PROXY") ?? httpsProxy;
  const noProxy = env("NO_PROXY");
  const lines = [
    "# Generated by bench/mirror.ts. Do not edit.",
    `storage: ${JSON.stringify(join(MIRROR_DIR, "storage"))}`,
    "max_body_size: 1000mb",
    "server:",
    "  keepAliveTimeout: 60",
    "uplinks:",
    "  npmjs:",
    "    url: https://registry.npmjs.org/",
    "    timeout: 120s",
    "    maxage: 30d",
    "    max_fails: 20",
    "    fail_timeout: 10s",
    "    cache: true",
    "    agent_options:",
    "      keepAlive: true",
    "      maxSockets: 64",
    "      maxFreeSockets: 16",
    "packages:",
    "  '@*/*':",
    "    access: $all",
    "    publish: $authenticated",
    "    proxy: npmjs",
    "  '**':",
    "    access: $all",
    "    publish: $authenticated",
    "    proxy: npmjs",
    "log:",
    "  type: stdout",
    "  format: pretty",
    "  level: warn",
  ];
  if (httpProxy) lines.push(`http_proxy: ${JSON.stringify(httpProxy)}`);
  if (httpsProxy) lines.push(`https_proxy: ${JSON.stringify(httpsProxy)}`);
  if (noProxy) lines.push(`no_proxy: ${JSON.stringify(noProxy)}`);
  writeFileSync(CONFIG_FILE, `${lines.join("\n")}\n`);
}

function readPid(): number | null {
  if (!existsSync(PID_FILE)) return null;
  const pid = Number(readFileSync(PID_FILE, "utf8").trim());
  if (!pid) return null;
  try {
    process.kill(pid, 0);
    return pid;
  } catch {
    return null;
  }
}

export async function startMirror(): Promise<void> {
  const url = registryUrl();
  if (await registryAlive(url)) return;
  if (url !== DEFAULT_REGISTRY) throw new Error(`BENCH_REGISTRY=${url} is not reachable`);
  writeConfig();
  const npx = which("npx");
  if (!npx) throw new Error("npx not found on PATH");
  log(`starting verdaccio@${VERDACCIO_VERSION} (log: ${LOG_FILE})`);
  const fd = openSync(LOG_FILE, "a");
  const child = spawn(
    npx,
    ["-y", `verdaccio@${VERDACCIO_VERSION}`, "--config", CONFIG_FILE, "--listen", "127.0.0.1:4873"],
    { detached: true, stdio: ["ignore", fd, fd], env: { ...process.env, NODE_OPTIONS: "--max-old-space-size=2048" } },
  );
  closeSync(fd);
  child.unref();
  writeFileSync(PID_FILE, String(child.pid));
  for (let i = 0; i < 240; i++) {
    if (await registryAlive(url)) {
      log("verdaccio is up");
      return;
    }
    await sleep(500);
  }
  throw new Error(`verdaccio did not come up in 120s, see ${LOG_FILE}`);
}

export function stopMirror(): void {
  const pid = readPid();
  if (!pid) return;
  try {
    process.kill(-pid, "SIGTERM"); // npx and verdaccio share the process group
  } catch {
    process.kill(pid, "SIGTERM");
  }
  rmrf(PID_FILE);
}

/** Install every fixture with npm so the mirror holds all metadata and tarballs. */
export function prewarm(fixtures?: string[]): void {
  const names = fixtures ?? readdirSync(FIXTURES_DIR).filter((n) => existsSync(join(FIXTURES_DIR, n, "package.json")));
  const npm = which("npm");
  if (!npm) throw new Error("npm not found on PATH");
  for (const name of names) {
    const work = join(TMP_DIR, "prewarm", name);
    const cache = join(TMP_DIR, "prewarm-cache");
    rmrf(work);
    cpSync(join(FIXTURES_DIR, name), work, { recursive: true });
    log(`prewarm: npm install ${name}`);
    const t0 = Date.now();
    runOk(
      [npm, "install", "--ignore-scripts", "--no-audit", "--no-fund", "--loglevel=error", "--registry", registryUrl()],
      { cwd: work, env: { ...process.env, npm_config_cache: cache, npm_config_update_notifier: "false" }, stdio: "inherit" },
    );
    log(`prewarm: ${name} done in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
    rmrf(work);
  }
}

async function main(): Promise<void> {
  const cmd = process.argv[2] ?? "status";
  if (cmd === "start") await startMirror();
  else if (cmd === "stop") stopMirror();
  else if (cmd === "status") {
    const alive = await registryAlive(registryUrl());
    console.log(alive ? `up ${registryUrl()}` : `down ${registryUrl()}`);
    process.exitCode = alive ? 0 : 1;
  } else if (cmd === "prewarm") {
    await startMirror();
    prewarm(process.argv.slice(3).length ? process.argv.slice(3) : undefined);
  } else {
    console.error("usage: node bench/mirror.ts start|stop|status|prewarm [fixture...]");
    process.exitCode = 2;
  }
}

if (isMain(import.meta.url)) await main();
