//! Lockfile printing: the yarn.lock v1 text bun prints for `bun ./bun.lockb` and writes with
//! `--yarn` / `install.lockfile.print = "yarn"` (port of bun `lockfile/printer/Yarn.rs`).

use fnpm_types::{LockGraph, Resolution};

use crate::flat::{Flat, INVALID, VTag, dependency_cmp, resolution_order};
use crate::hash::{format_meta_hash, meta_hash, resolution_text};
use crate::json_out::{escaped, quoted};

/// Options for [`yarn_v1`].
#[derive(Debug, Clone)]
pub struct YarnOptions {
    /// The registry used to spell out default tarball locations (`resolved`).
    pub registry: String,
    /// The comment naming the source file (`# fnpm ./fnpm.lock --hash: ...`).
    pub source: String,
}

impl Default for YarnOptions {
    fn default() -> Self {
        Self {
            registry: "https://registry.npmjs.org/".to_owned(),
            source: "fnpm ./fnpm.lock".to_owned(),
        }
    }
}

/// bun `strings::must_escape_yaml_string`.
pub(crate) fn must_escape_yaml(s: &str) -> bool {
    let b = s.as_bytes();
    let Some(&first) = b.first() else { return true };
    if !first.is_ascii_alphabetic() {
        return true;
    }
    s.starts_with("Yes")
        || s.starts_with("No")
        || s.starts_with("true")
        || s.starts_with("false")
        || b[1..]
            .iter()
            .any(|c| b": \t\r\n\x0B\x0C\\\",[]".contains(c))
}

fn vtag_number(t: VTag) -> u8 {
    match t {
        VTag::Uninitialized => 0,
        VTag::Npm => 1,
        VTag::DistTag => 2,
        VTag::Tarball => 3,
        VTag::Folder => 4,
        VTag::Symlink => 5,
        VTag::Workspace => 6,
        VTag::Git => 7,
        VTag::Github => 8,
        VTag::Catalog => 9,
    }
}

/// `<registry>/<name>/-/<unscoped name>-<version>.tgz`.
pub fn default_tarball_url(registry: &str, name: &str, version: &str) -> String {
    let registry = registry.trim_end_matches('/');
    let unscoped = fnpm_types::name::unscoped_package_name(name);
    format!("{registry}/{name}/-/{unscoped}-{version}.tgz")
}

fn resolved_url(r: &Resolution, name: &str, registry: &str) -> String {
    match r {
        Resolution::Npm {
            version,
            tarball_url,
            ..
        } => tarball_url
            .clone()
            .unwrap_or_else(|| default_tarball_url(registry, name, version)),
        other => resolution_text(other),
    }
}

/// Prints the graph as yarn.lock v1.
pub fn yarn_v1(graph: &LockGraph, opts: &YarnOptions) -> String {
    let mut out = String::with_capacity(64 + graph.packages.len() * 160);
    out.push_str(
        "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n# ",
    );
    out.push_str(&opts.source);
    out.push_str(" --hash: ");
    out.push_str(&format_meta_hash(&meta_hash(graph)));
    out.push_str("\n\n");
    if graph.packages.is_empty() {
        return out;
    }
    let flat = Flat::new(graph);
    let n = graph.packages.len();
    let mut requested: Vec<Vec<u32>> = vec![Vec::new(); n];
    for (d, &p) in flat.resolutions.iter().enumerate() {
        if (p as usize) < n {
            requested[p as usize].push(d as u32);
        }
    }
    let requested_as = |d: u32| -> &str {
        let dep = &flat.deps[d as usize];
        if dep.literal.is_empty() && dep.version.tag == VTag::Workspace {
            return dep.workspace_path.as_deref().unwrap_or(dep.version.value);
        }
        dep.literal
    };
    let requested_name = |d: u32| -> &str {
        if requested_as(d).starts_with("npm:") {
            flat.deps[d as usize].name
        } else {
            &graph.packages[flat.resolutions[d as usize] as usize].name
        }
    };
    for list in requested.iter_mut().skip(1) {
        list.sort_by(|&a, &b| {
            requested_name(a)
                .as_bytes()
                .cmp(requested_name(b).as_bytes())
                .then(
                    vtag_number(flat.deps[a as usize].version.tag)
                        .cmp(&vtag_number(flat.deps[b as usize].version.tag)),
                )
                .then(requested_as(a).as_bytes().cmp(requested_as(b).as_bytes()))
        });
    }
    let mut ids: Vec<usize> = (1..n).collect();
    ids.sort_unstable_by(|&a, &b| {
        let (pa, pb) = (&graph.packages[a], &graph.packages[b]);
        pa.name
            .as_bytes()
            .cmp(pb.name.as_bytes())
            .then_with(|| resolution_order(&pa.resolution, &pb.resolution))
    });

    for i in ids {
        let p = &graph.packages[i];
        let version = resolution_text(&p.resolution);
        out.push('\n');
        let reqs = &requested[i];
        let mut needs_comma = false;
        for (nth, &r) in reqs.iter().enumerate() {
            let (name, spec) = (requested_name(r), requested_as(r));
            if reqs[..nth]
                .iter()
                .any(|&e| requested_name(e) == name && requested_as(e) == spec)
            {
                continue;
            }
            if needs_comma {
                out.push_str(", ");
            }
            let needs_quote = must_escape_yaml(name)
                || spec.bytes().any(|c| b" |\t-/!:\"\\,\n\r".contains(&c))
                || spec.starts_with("npm:");
            if needs_quote {
                out.push('"');
                escaped(&mut out, name);
            } else {
                out.push_str(name);
            }
            out.push('@');
            if spec.is_empty() {
                out.push('^');
                out.push_str(&version);
            } else if needs_quote {
                escaped(&mut out, spec);
            } else {
                out.push_str(spec);
            }
            if needs_quote {
                out.push('"');
            }
            needs_comma = true;
        }
        out.push_str(":\n  version ");
        quoted(&mut out, &version);
        out.push_str("\n  resolved ");
        quoted(
            &mut out,
            &resolved_url(&p.resolution, &p.name, &opts.registry),
        );
        out.push('\n');
        if let Some(i) = p.resolution.integrity() {
            out.push_str("  integrity ");
            out.push_str(&i.to_sri());
            out.push('\n');
        }
        let mut deps: Vec<u32> = flat.list(i as u32).collect();
        deps.sort_by(|&a, &b| dependency_cmp(&flat.deps[a as usize], &flat.deps[b as usize]));
        let mut group = "";
        for d in deps {
            let dep = &flat.deps[d as usize];
            let g = if dep.behavior.is_optional() {
                "  optionalDependencies:\n"
            } else if dep.behavior.is_prod() {
                "  dependencies:\n"
            } else if dep.behavior.is_dev() {
                "  devDependencies:\n"
            } else {
                continue;
            };
            if g != group {
                out.push_str(g);
                group = g;
            }
            out.push_str("    ");
            if must_escape_yaml(dep.name) {
                quoted(&mut out, dep.name);
            } else {
                out.push_str(dep.name);
            }
            out.push(' ');
            quoted(&mut out, dep.literal);
            out.push('\n');
        }
        let _ = INVALID;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use fnpm_types::{Behavior, DepEdge, HashAlgorithm, Integrity, Package, PackageId};

    #[test]
    fn yaml_escaping() {
        assert!(must_escape_yaml("@babel/core"));
        assert!(must_escape_yaml("true-thing"));
        assert!(!must_escape_yaml("lodash"));
        assert!(must_escape_yaml("a:b"));
        assert!(must_escape_yaml(""));
    }

    #[test]
    fn prints_like_bun() {
        let mut g = LockGraph::new(Package::new("app", "", Resolution::Root));
        let i = Integrity::compute(HashAlgorithm::Sha512, b"x");
        let a = g.push(Package::new(
            "a",
            "1.0.0",
            Resolution::npm("1.0.0", Some(i)),
        ));
        let s = g.push(Package::new(
            "@s/b",
            "2.0.0",
            Resolution::npm("2.0.0", None),
        ));
        let mut e1 = DepEdge::new("a", "^1.0.0", Behavior::PROD);
        e1.target = Some(a);
        let mut e2 = DepEdge::new("@s/b", "~2.0.0", Behavior::DEV);
        e2.target = Some(s);
        g.root_mut().dependencies = vec![e2, e1];
        let mut e3 = DepEdge::new("@s/b", "2.0.0", Behavior::OPTIONAL);
        e3.target = Some(PackageId(s.0));
        g.packages[a.index()].dependencies.push(e3);
        let text = yarn_v1(&g, &YarnOptions::default());
        let body = text.split_once("\n\n").unwrap().1;
        assert_eq!(
            body,
            format!(
                "\n\"@s/b@2.0.0\", \"@s/b@~2.0.0\":\n  version \"2.0.0\"\n  resolved \"https://registry.npmjs.org/@s/b/-/b-2.0.0.tgz\"\n\na@^1.0.0:\n  version \"1.0.0\"\n  resolved \"https://registry.npmjs.org/a/-/a-1.0.0.tgz\"\n  integrity {}\n  optionalDependencies:\n    \"@s/b\" \"2.0.0\"\n",
                i.to_sri()
            )
        );
        assert!(text.starts_with("# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n# fnpm ./fnpm.lock --hash: "));
    }
}
