#[test]
fn yarn_stuff_protocols() {
    let m = migrate_dir(&fixtures().join("yarn/yarn-stuff"));
    let lock = snapshot(
        SNAP,
        "bun pm migrate for existing yarn.lock yarn-stuff: yarn-stuff 1",
    );
    assert_matches_bun_lock(&m.graph, &lock, REGISTRY);
    let by_alias = |alias: &str| {
        let e = m.graph.root().dependency(alias).unwrap();
        &m.graph.packages[e.target.unwrap().index()]
    };
    assert!(
        matches!(&by_alias("full-git-url").resolution, Resolution::Github { owner, repo, resolved_commit, .. }
        if owner == "isaacs" && repo == "abbrev-js" && resolved_commit == "3f9802e56ff878761a338e43ecacbfed39d2181d")
    );
    assert_eq!(by_alias("full-git-url").name, "abbrev-js");
    assert!(
        matches!(&by_alias("ghshort").resolution, Resolution::RemoteTarball { url, .. } if url.starts_with("https://codeload.github.com/"))
    );
    assert_eq!(by_alias("old").resolution.npm_version(), Some("1.0.9"));
    assert_eq!(by_alias("pinned").name, "abbrev");
    assert_eq!(
        m.graph.root().dependency("pinned").unwrap().target,
        m.graph.root().dependency("reg").unwrap().target
    );
    assert_eq!(by_alias("remote").name, "abbrev");
    assert!(
        matches!(&by_alias("tarball").resolution, Resolution::LocalTarball { path, integrity: Some(i) }
        if path == "abbrev-1.1.1.tgz" && i.to_sri().starts_with("sha1-"))
    );
    // yarn.lock records no bins; a file: folder reads them from its package.json on disk
    assert!(by_alias("symlink").bin.is_none());
}

