#[test]
fn detect_and_dispatch() {
    assert_eq!(
        yarn_v1::detect(SIMPLE_LOCK.as_bytes()),
        Some(Format::YarnV1)
    );
    assert_eq!(
        yarn_v1::detect(b"__metadata:\n  version: 8\n"),
        Some(Format::YarnBerry)
    );
    assert_eq!(
        yarn_v1::detect(b"# comment\n\n__metadata:\n  version: 8\n"),
        Some(Format::YarnBerry)
    );
    // yarn reads a file as v1 only when the marker is in the comment lines at its top
    assert_eq!(
        yarn_v1::detect(b"# yarn lockfile v1\n__metadata:\n  version: 8\n"),
        Some(Format::YarnV1)
    );
    assert_eq!(
        yarn_v1::detect(b"__metadata:\n  version: 8\n\"a@npm:1\":\n  x: \"# yarn lockfile v1\"\n"),
        Some(Format::YarnBerry)
    );
    assert_eq!(yarn_v1::detect(b"foo@1:\n  version \"1\"\n"), None);
    let dir = project(&[
        ("package.json", "{}"),
        ("yarn.lock", "foo@^1:\n  version \"1.0.0\"\n"),
    ]);
    let ws = workspace(dir.path());
    let files = ScopedFiles(dir.path().to_path_buf());
    assert!(yarn_v1::migrate(b"foo@^1:\n  version \"1.0.0\"\n", &ws, &options(&files)).is_err());
}

const ALIASES_LOCK: &str = "# yarn lockfile v1

\"@scope/real@^2.0.0\", \"aliased@npm:@scope/real@^2.0.0\":
  version \"2.1.0\"
  resolved \"https://registry.yarnpkg.com/@scope/real/-/real-2.1.0.tgz#0000000000000000000000000000000000000000\"
  integrity sha512-41Cifkg6e8TylSpdtTpeLVMqvSBEVzTttHvERD741+pnZ8ANv0004MRL43QKPDlK9cGvNp6NZWZUBlbGXYxxng==

\"other@npm:left-pad@1.3.0\":
  version \"1.3.0\"
  resolved \"https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#5b8a3a7765dfe001261dde915589e782f8c94d1e\"
";

#[test]
fn npm_aliases_resolve_to_the_real_package() {
    let m = migrate_project(&[
        (
            "package.json",
            r#"{ "name": "a", "dependencies": { "aliased": "npm:@scope/real@^2.0.0", "other": "npm:left-pad@1.3.0", "@scope/real": "^2.0.0" } }"#,
        ),
        ("yarn.lock", ALIASES_LOCK),
    ]);
    let g = &m.graph;
    let target =
        |name: &str| &g.packages[g.root().dependency(name).unwrap().target.unwrap().index()];
    assert_eq!(target("aliased").name, "@scope/real");
    assert_eq!(target("@scope/real").name, "@scope/real");
    assert_eq!(
        g.root().dependency("aliased").unwrap().target,
        g.root().dependency("@scope/real").unwrap().target
    );
    assert_eq!(target("other").name, "left-pad");
    // without an integrity line the sha1 after `#` of `resolved` is the integrity
    assert_eq!(
        target("other").resolution.integrity().unwrap().to_sri(),
        "sha1-W4o6d2Xf4AEmHd6RVYnngvjJTR4="
    );
    assert_eq!(g.len(), 3);
}

#[test]
fn workspaces_link_and_missing_entries_are_dropped() {
    let m = migrate_project(&[
        (
            "package.json",
            r#"{ "name": "root", "workspaces": ["packages/*"], "dependencies": { "is-number": "^7.0.0", "missing": "^1.0.0", "lib": "workspace:*" } }"#,
        ),
        (
            "packages/lib/package.json",
            r#"{ "name": "lib", "version": "1.2.0", "dependencies": { "is-number": "^7.0.0" } }"#,
        ),
        (
            "packages/app/package.json",
            r#"{ "name": "app", "version": "0.0.1", "dependencies": { "lib": "^1.0.0" }, "peerDependencies": { "is-number": "*" } }"#,
        ),
        ("yarn.lock", SIMPLE_LOCK),
    ]);
    let g = &m.graph;
    assert_eq!(g.workspaces.len(), 3);
    let root = g.root();
    // `missing` has no yarn.lock entry: dropped so the install resolves it
    assert!(root.dependency("missing").is_none());
    assert!(
        m.warnings
            .iter()
            .any(|w| w.contains("yarn.lock missing \"missing@^1.0.0\""))
    );
    let lib = g.workspaces["packages/lib"];
    let lib_edge = root.dependency("lib").unwrap();
    assert_eq!(lib_edge.target, Some(lib));
    assert!(lib_edge.behavior.contains(Behavior::WORKSPACE));
    let app = &g.packages[g.workspaces["packages/app"].index()];
    // `^1.0.0` has no entry; the workspace satisfies it, and an importer needs the exact key
    assert!(app.dependency("lib").is_none());
    // the peer binds like bun.lock's loader binds it
    assert_eq!(
        app.dependency("is-number").unwrap().target,
        root.dependency("is-number").unwrap().target
    );
}

#[test]
fn transitive_ranges_link_to_workspaces() {
    let lock = "# yarn lockfile v1

uses-lib@^1.0.0:
  version \"1.0.0\"
  resolved \"https://registry.yarnpkg.com/uses-lib/-/uses-lib-1.0.0.tgz\"
  dependencies:
    lib \"^1.0.0\"
    gone \"^2\"
";
    let m = migrate_project(&[
        (
            "package.json",
            r#"{ "name": "root", "workspaces": ["packages/*"], "dependencies": { "uses-lib": "^1.0.0" } }"#,
        ),
        (
            "packages/lib/package.json",
            r#"{ "name": "lib", "version": "1.2.0" }"#,
        ),
        ("yarn.lock", lock),
    ]);
    let g = &m.graph;
    let uses = g.root().dependency("uses-lib").unwrap().target.unwrap();
    let pkg = &g.packages[uses.index()];
    let lib = pkg.dependency("lib").unwrap();
    assert_eq!(lib.target, Some(g.workspaces["packages/lib"]));
    assert!(lib.behavior.contains(Behavior::WORKSPACE));
    assert_eq!(pkg.dependency("gone").unwrap().target, None);
    assert_eq!(pkg.resolution.npm_version(), Some("1.0.0"));
    assert!(matches!(
        &pkg.resolution,
        Resolution::Npm {
            tarball_url: None,
            integrity: None,
            ..
        }
    ));
}

#[test]
fn private_registry_urls_and_platforms() {
    let lock = "# yarn lockfile v1

fsevents@^2.3.2:
  version \"2.3.2\"
  resolved \"https://npm.example.com/fsevents/-/fsevents-2.3.2.tgz#00\"
  integrity sha512-xiqMQR4xAeHTuB9uWm+fFRcIOgKBMiOBP+eXiyT7jsgVCq1bkVygt00oASowB7EdtpOHaaPgKt812P9ab+DDKA==
  os [\"darwin\"]
  cpu [\"x64\", \"arm64\"]

\"cdn@https://cdn.example.com/cdn-1.0.0.tgz\":
  version \"1.0.0\"
  resolved \"https://cdn.example.com/cdn-1.0.0.tgz#abc\"

\"bad@^1\":
  version \"not-a-version\"
";
    let m = migrate_project(&[
        (
            "package.json",
            r#"{ "dependencies": { "fsevents": "^2.3.2", "cdn": "https://cdn.example.com/cdn-1.0.0.tgz", "bad": "^1" } }"#,
        ),
        ("yarn.lock", lock),
    ]);
    let g = &m.graph;
    let fsevents = &g.packages[g
        .root()
        .dependency("fsevents")
        .unwrap()
        .target
        .unwrap()
        .index()];
    assert!(
        matches!(&fsevents.resolution, Resolution::Npm { tarball_url: Some(u), .. } if u == "https://npm.example.com/fsevents/-/fsevents-2.3.2.tgz")
    );
    assert!(!fsevents.platform.is_any());
    let cdn = &g.packages[g.root().dependency("cdn").unwrap().target.unwrap().index()];
    assert_eq!(
        cdn.resolution,
        Resolution::RemoteTarball {
            url: "https://cdn.example.com/cdn-1.0.0.tgz".into(),
            integrity: None
        }
    );
    assert!(g.root().dependency("bad").is_none());
    assert!(
        m.warnings
            .iter()
            .any(|w| w.contains("skipping \"bad@^1\" from yarn.lock: invalid version"))
    );
}

#[test]
fn consolidates_duplicate_blocks() {
    let lock = "# yarn lockfile v1

a@^1.0.0:
  version \"1.0.0\"
  resolved \"https://registry.yarnpkg.com/a/-/a-1.0.0.tgz\"

a@~1.0.0:
  version \"1.0.0\"
  resolved \"https://registry.yarnpkg.com/a/-/a-1.0.0.tgz\"
";
    let m = migrate_project(&[
        (
            "package.json",
            r#"{ "dependencies": { "a": "^1.0.0" }, "devDependencies": { "b": "npm:a@~1.0.0" } }"#,
        ),
        ("yarn.lock", lock),
    ]);
    assert_eq!(m.graph.len(), 2);
    let specs = yarn_v1_specs(lock);
    assert_eq!(specs["a"], vec!["a@^1.0.0", "a@~1.0.0"]);
}

fn yarn_v1_specs(text: &str) -> BTreeMap<String, Vec<String>> {
    let mut out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for line in text
        .lines()
        .filter(|l| !l.starts_with(' ') && l.ends_with(':') && !l.starts_with('#'))
    {
        for spec in line.trim_end_matches(':').split(", ") {
            let spec = spec.trim_matches('"');
            let name = if let Some(rest) = spec.strip_prefix('@') {
                format!("@{}", rest.split('@').next().unwrap())
            } else {
                spec.split('@').next().unwrap().to_owned()
            };
            out.entry(name).or_default().push(spec.to_owned());
        }
    }
    out
}

#[test]
fn export_round_trips() {
    for folder in ["yarn-cli-repo", "yarn-stuff", "yarn-lock-mkdirp"] {
        let dir = fixtures().join("yarn").join(folder);
        let m = migrate_dir(&dir);
        let text = yarn_v1::serialize(&m.graph);
        assert!(text.starts_with(
            "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n"
        ));
        let ws = workspace(&dir);
        let files = ScopedFiles(dir.clone());
        let again = yarn_v1::migrate(text.as_bytes(), &ws, &options(&files)).unwrap();
        let ids = |g: &fnpm_types::LockGraph| {
            let mut v: Vec<(String, Option<String>)> = g
                .packages
                .iter()
                .map(|p| (bun_id(p), p.resolution.integrity().map(|i| i.to_sri())))
                .collect();
            v.sort();
            v
        };
        assert_eq!(ids(&again.graph), ids(&m.graph), "{folder}");
        let edges = |g: &fnpm_types::LockGraph| {
            let mut v: Vec<(String, String, Option<String>)> = g
                .packages
                .iter()
                .flat_map(|p| {
                    p.dependencies.iter().map(move |e| {
                        (
                            bun_id(p),
                            e.name.clone(),
                            e.target.map(|t| bun_id(&g.packages[t.index()])),
                        )
                    })
                })
                .collect();
            v.sort();
            v
        };
        assert_eq!(edges(&again.graph), edges(&m.graph), "{folder}");
        assert_eq!(yarn_v1::serialize(&again.graph), text, "{folder}: stable");
    }
}

