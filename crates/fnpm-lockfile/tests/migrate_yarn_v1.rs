const SNAP: &str = "yarn-lock-migration.test.ts.snap";
const REGISTRY: &str = "https://registry.npmjs.org/";

fn migrate_dir(dir: &Path) -> Migration {
    let ws = workspace(dir);
    let files = ScopedFiles(dir.to_path_buf());
    let bytes = std::fs::read(dir.join("yarn.lock")).unwrap();
    yarn_v1::migrate(&bytes, &ws, &options(&files)).unwrap()
}

/// A project written to a temp dir.
fn project(files: &[(&str, &str)]) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    for (path, text) in files {
        let p = dir.path().join(path);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, text).unwrap();
    }
    dir
}

fn migrate_project(files: &[(&str, &str)]) -> Migration {
    let dir = project(files);
    migrate_dir(dir.path())
}

#[test]
fn existing_fixtures_match_bun_snapshots() {
    for folder in [
        "yarn-cli-repo",
        "yarn-lock-mkdirp",
        "yarn-lock-mkdirp-no-resolved",
    ] {
        let m = migrate_dir(&fixtures().join("yarn").join(folder));
        let lock = snapshot(
            SNAP,
            &format!("bun pm migrate for existing yarn.lock {folder}: {folder} 1"),
        );
        assert_matches_bun_lock(&m.graph, &lock, REGISTRY);
        assert_eq!(m.graph.config_version, ConfigVersion::V0);
    }
}

#[test]
fn yarn_cli_repo_scale() {
    let m = migrate_dir(&fixtures().join("yarn/yarn-cli-repo"));
    let lock = snapshot(
        SNAP,
        "bun pm migrate for existing yarn.lock yarn-cli-repo: yarn-cli-repo 1",
    );
    let unique: std::collections::BTreeSet<&str> = lock["packages"]
        .as_object()
        .unwrap()
        .values()
        .map(|t| t[0].as_str().unwrap())
        .collect();
    assert_eq!(m.graph.len() - 1, unique.len());
    assert!(m.graph.len() > 1000);
}

