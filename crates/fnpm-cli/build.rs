//! Generates the launcher's command tables from `cli-spec.json`.
//!
//! The spec is written by `npm run build:spec` in `packages/fuck-npm` from the TS command
//! registry and committed, so building never needs Node. This script turns it into `match`
//! based lookups (`$OUT_DIR/spec.rs`, included by `src/spec.rs`): nothing is parsed at run
//! time. Each function mirrors a helper of `packages/fuck-npm/src/cli/{registry,plan,
//! foreign-flags}.ts` evaluated ahead of time for one command, and the comments name it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;

/// Leaves of the `fnpm` root that run natively (`docs/DECISIONS.md` #2).
const NATIVE: [&str; 5] = ["install", "ci", "add", "remove", "update"];

#[derive(Clone)]
struct Flag {
    key: String,
    raw: String,
    long: String,
    short: Option<char>,
    takes_value: bool,
    optional_value: bool,
    repeatable: bool,
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let spec_path = manifest.join("cli-spec.json");
    println!("cargo:rerun-if-changed={}", spec_path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string(&spec_path)
        .unwrap_or_else(|error| panic!("reading {}: {error}", spec_path.display()));
    let spec: Value = serde_json::from_str(&text).expect("cli-spec.json is not valid JSON");

    let flags: Vec<Flag> = spec["flags"]
        .as_array()
        .expect("flags")
        .iter()
        .map(|flag| Flag {
            key: str_of(&flag["key"]),
            raw: str_of(&flag["raw"]),
            long: str_of(&flag["long"]),
            short: flag["short"].as_str().map(|short| {
                let mut chars = short.chars();
                let letter = chars.next().expect("empty short name");
                assert!(
                    chars.next().is_none(),
                    "short name {short:?} is not one letter"
                );
                letter
            }),
            takes_value: flag["takesValue"].as_bool().expect("takesValue"),
            optional_value: flag["optionalValue"].as_bool().unwrap_or(false),
            repeatable: flag["repeatable"].as_bool().unwrap_or(false),
        })
        .collect();

    let mut out = String::new();
    out.push_str("// @generated by crates/fnpm-cli/build.rs from cli-spec.json. Do not edit.\n\n");
    let version = str_of(&spec["version"]);
    writeln!(
        out,
        "/// The npm package version (`packages/fuck-npm/package.json`)."
    )
    .unwrap();
    writeln!(out, "pub const VERSION: &str = {version:?};\n").unwrap();

    writeln!(out, "/// Every flag of both command trees, deduplicated.").unwrap();
    writeln!(out, "pub static FLAGS: [FlagDef; {}] = [", flags.len()).unwrap();
    for flag in &flags {
        writeln!(
            out,
            "    FlagDef {{ key: {:?}, long: {:?}, short: {:?}, takes_value: {}, optional_value: {}, repeatable: {} }},",
            flag.key, flag.long, flag.short, flag.takes_value, flag.optional_value, flag.repeatable
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    let foreign = &spec["foreignFlags"];
    let rewrites: Vec<(String, Option<String>)> = foreign["rewrites"]
        .as_array()
        .expect("rewrites")
        .iter()
        .map(|pair| (str_of(&pair[0]), pair[1].as_str().map(str::to_owned)))
        .collect();
    let update_filters: BTreeSet<String> = strings(&foreign["updateFilters"]).into_iter().collect();
    write_set(
        &mut out,
        "ignored_foreign_flag",
        "`IGNORED_FOREIGN_FLAGS`",
        &strings(&foreign["ignoredFlags"]),
    );
    write_set(
        &mut out,
        "ignored_foreign_option",
        "`IGNORED_FOREIGN_OPTIONS`",
        &strings(&foreign["ignoredOptions"]),
    );
    let prefixes = strings(&foreign["ignoredPrefixes"]);
    writeln!(out, "/// `IGNORED_FOREIGN_PREFIXES`.\npub static IGNORED_FOREIGN_PREFIXES: [&str; {}] = {:?};\n", prefixes.len(), prefixes).unwrap();
    let runtime = &spec["runtimeFlags"];
    write_set(
        &mut out,
        "ignored_runtime_flag",
        "`IGNORED_RUNTIME_FLAGS`",
        &strings(&runtime["ignored"]),
    );
    let runtime_short = str_of(&runtime["short"]);
    writeln!(out, "/// `IGNORED_RUNTIME_SHORT`, with its dash.\npub const IGNORED_RUNTIME_SHORT: &str = {:?};\n", format!("-{runtime_short}")).unwrap();

    for (bin, ident) in [("fnpm", "FNPM"), ("fnpm-lock", "FNPM_LOCK")] {
        let bin_spec = &spec["bins"][bin];
        let root = &bin_spec["root"];
        let globals: Vec<usize> = indexes(&bin_spec["globalFlags"]);
        let prefix = ident.to_lowercase();

        // flagSpecsFor(root): collectFlags(root) (deduped by key, first wins) + globals.
        let mut union: Vec<usize> = Vec::new();
        let mut keys = BTreeSet::new();
        collect_leaf_flags(root, &mut |index| {
            if keys.insert(flags[index].key.clone()) {
                union.push(index);
            }
        });
        union.extend(&globals);
        write_index(&mut out, &format!("{prefix}_root"), &flags, &union);

        // Root children: native leaves get their own tables, everything else is `Other`.
        let mut child_arms = Vec::new();
        for child in root["children"].as_array().expect("children") {
            let name = str_of(&child["name"]);
            let mut spellings = vec![name.clone()];
            spellings.extend(strings(&child["aliases"]));
            let native = bin == "fnpm" && NATIVE.contains(&name.as_str());
            let target = if native {
                assert_eq!(
                    child["kind"], "leaf",
                    "native command {name} must be a leaf"
                );
                format!("RootChild::Native(&LEAF_{})", name.to_uppercase())
            } else {
                "RootChild::Other".to_owned()
            };
            child_arms.push((spellings, target));
        }
        writeln!(
            out,
            "fn {prefix}_root_child(segment: &str) -> Option<RootChild> {{\n    match segment {{"
        )
        .unwrap();
        for (spellings, target) in &child_arms {
            let pattern = spellings
                .iter()
                .map(|s| format!("{s:?}"))
                .collect::<Vec<_>>()
                .join(" | ");
            writeln!(out, "        {pattern} => Some({target}),").unwrap();
        }
        out.push_str("        _ => None,\n    }\n}\n\n");

        let aliases: Vec<String> = bin_spec["aliases"]
            .as_array()
            .expect("aliases")
            .iter()
            .map(|alias| str_of(&alias["name"]))
            .collect();
        write_set(
            &mut out,
            &format!("{prefix}_root_alias"),
            "Top-level shorthands (`registry.aliases`)",
            &aliases,
        );

        // flagOwners(registry), with preferredSpelling for alias targets.
        let alias_targets: Vec<(String, Vec<String>)> = bin_spec["aliases"]
            .as_array()
            .unwrap()
            .iter()
            .map(|alias| (str_of(&alias["name"]), strings(&alias["target"])))
            .collect();
        let mut owners: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for child in root["children"].as_array().unwrap() {
            walk_owners(
                child,
                vec![str_of(&child["name"])],
                &alias_targets,
                &flags,
                &mut owners,
            );
        }
        writeln!(
            out,
            "fn {prefix}_flag_owners(name: &str) -> &'static [&'static str] {{\n    match name {{"
        )
        .unwrap();
        for (name, paths) in &owners {
            writeln!(out, "        {name:?} => &{paths:?},").unwrap();
        }
        out.push_str("        _ => &[],\n    }\n}\n\n");

        if bin == "fnpm" {
            for child in root["children"].as_array().unwrap() {
                let name = str_of(&child["name"]);
                if !NATIVE.contains(&name.as_str()) {
                    continue;
                }
                write_leaf(
                    &mut out,
                    child,
                    &flags,
                    &globals,
                    &rewrites,
                    &update_filters,
                );
            }
            for name in NATIVE {
                assert!(
                    root["children"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .any(|child| child["name"] == name),
                    "native command {name} is missing from the fnpm tree"
                );
            }
        }

        writeln!(
            out,
            "/// The `{bin}` bin.\npub static {ident}: BinDef = BinDef {{\n    name: {bin:?},\n    root_long: {prefix}_root_long,\n    root_short: {prefix}_root_short,\n    root_child: {prefix}_root_child,\n    root_alias: {prefix}_root_alias,\n    flag_owners: {prefix}_flag_owners,\n}};\n"
        )
        .unwrap();
    }

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("spec.rs"), out).expect("writing spec.rs");
}

fn str_of(value: &Value) -> String {
    value
        .as_str()
        .unwrap_or_else(|| panic!("expected a string, got {value}"))
        .to_owned()
}

fn strings(value: &Value) -> Vec<String> {
    value
        .as_array()
        .map(|items| items.iter().map(str_of).collect())
        .unwrap_or_default()
}

fn indexes(value: &Value) -> Vec<usize> {
    value
        .as_array()
        .map(|items| {
            items
                .iter()
                .map(|item| item.as_u64().expect("flag index") as usize)
                .collect()
        })
        .unwrap_or_default()
}

fn collect_leaf_flags(node: &Value, visit: &mut dyn FnMut(usize)) {
    if node["kind"] == "leaf" {
        for index in indexes(&node["flags"]) {
            visit(index);
        }
        return;
    }
    for child in node["children"].as_array().into_iter().flatten() {
        collect_leaf_flags(child, visit);
    }
}

fn walk_owners(
    node: &Value,
    path: Vec<String>,
    aliases: &[(String, Vec<String>)],
    flags: &[Flag],
    owners: &mut BTreeMap<String, Vec<String>>,
) {
    if node["kind"] == "leaf" {
        let owner = aliases
            .iter()
            .find(|(_, target)| *target == path)
            .map(|(name, _)| name.clone())
            .unwrap_or_else(|| path.join(" "));
        for index in indexes(&node["flags"]) {
            for name in accepted_flag_names(&flags[index].raw) {
                let entry = owners.entry(name).or_default();
                if !entry.contains(&owner) {
                    entry.push(owner.clone());
                }
            }
        }
        return;
    }
    for child in node["children"].as_array().into_iter().flatten() {
        let mut next = path.clone();
        next.push(str_of(&child["name"]));
        walk_owners(child, next, aliases, flags, owners);
    }
}

/// `camelize` in registry.ts.
fn camelize(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut chars = value.chars().peekable();
    while let Some(char) = chars.next() {
        if char == '-'
            && let Some(&next) = chars.peek()
            && (next.is_ascii_lowercase() || next.is_ascii_digit())
        {
            out.push(next.to_ascii_uppercase());
            chars.next();
            continue;
        }
        out.push(char);
    }
    out
}

/// `raw` without its `[placeholder]` / `<placeholder>` parts.
fn strip_placeholders(raw: &str) -> String {
    let mut out = String::new();
    let mut chars = raw.chars().peekable();
    while let Some(char) = chars.next() {
        if char == '<' || char == '[' {
            let rest: String = chars.clone().collect();
            if let Some(end) = rest.find(['>', ']']) {
                let inner = &rest[..end];
                if !inner.contains(['>', ']']) {
                    for _ in 0..=inner.chars().count() {
                        chars.next();
                    }
                    continue;
                }
            }
        }
        out.push(char);
    }
    out
}

/// `acceptedFlagNames` in registry.ts.
fn accepted_flag_names(raw: &str) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    let mut add = |name: String| {
        if !names.contains(&name) {
            names.push(name);
        }
    };
    for part in strip_placeholders(raw).split(',') {
        let trimmed = part.trim();
        let trimmed = trimmed
            .strip_prefix("--")
            .or_else(|| trimmed.strip_prefix('-'))
            .unwrap_or(trimmed);
        if trimmed.is_empty() {
            continue;
        }
        add(trimmed.to_owned());
        add(camelize(trimmed));
        if let Some(positive) = trimmed.strip_prefix("no-") {
            add(positive.to_owned());
            add(camelize(positive));
        }
    }
    names
}

fn write_set(out: &mut String, name: &str, doc: &str, values: &[String]) {
    writeln!(out, "/// {doc}.\npub fn {name}(value: &str) -> bool {{").unwrap();
    if values.is_empty() {
        out.push_str("    let _ = value;\n    false\n}\n\n");
        return;
    }
    let unique: BTreeSet<&String> = values.iter().collect();
    let pattern = unique
        .iter()
        .map(|value| format!("{value:?}"))
        .collect::<Vec<_>>()
        .join("\n            | ");
    writeln!(
        out,
        "    matches!(\n        value,\n        {pattern}\n    )\n}}\n"
    )
    .unwrap();
}

/// Long and short lookups over a spec list, first spelling wins (`specIndex` in plan.ts).
fn write_index(out: &mut String, prefix: &str, flags: &[Flag], list: &[usize]) {
    let mut longs: Vec<(String, usize)> = Vec::new();
    let mut shorts: Vec<(char, usize)> = Vec::new();
    for &index in list {
        let flag = &flags[index];
        if !longs.iter().any(|(long, _)| *long == flag.long) {
            longs.push((flag.long.clone(), index));
        }
        if let Some(short) = flag.short
            && !shorts.iter().any(|(letter, _)| *letter == short)
        {
            shorts.push((short, index));
        }
    }
    writeln!(
        out,
        "fn {prefix}_long(name: &str) -> Option<&'static FlagDef> {{\n    match name {{"
    )
    .unwrap();
    for (long, index) in &longs {
        writeln!(out, "        {long:?} => Some(&FLAGS[{index}]),").unwrap();
    }
    out.push_str("        _ => None,\n    }\n}\n\n");
    writeln!(
        out,
        "fn {prefix}_short(letter: char) -> Option<&'static FlagDef> {{\n    match letter {{"
    )
    .unwrap();
    for (short, index) in &shorts {
        writeln!(out, "        {short:?} => Some(&FLAGS[{index}]),").unwrap();
    }
    out.push_str("        _ => None,\n    }\n}\n\n");
}

fn write_leaf(
    out: &mut String,
    leaf: &Value,
    flags: &[Flag],
    globals: &[usize],
    rewrites: &[(String, Option<String>)],
    update_filters: &BTreeSet<String>,
) {
    let name = str_of(&leaf["name"]);
    let ident = name.replace('-', "_");
    let upper = ident.to_uppercase();
    let own: Vec<usize> = indexes(&leaf["flags"]);
    let mut specs = own.clone();
    specs.extend(globals);
    write_index(out, &format!("leaf_{ident}"), flags, &specs);

    // allowedFlagNames(leaf, registry).
    let mut allowed: Vec<String> = Vec::new();
    for &index in &specs {
        allowed.extend(accepted_flag_names(&flags[index].raw));
        if !flags[index].takes_value {
            allowed.push(format!("no-{}", flags[index].long));
        }
    }
    write_set(
        out,
        &format!("leaf_{ident}_allowed"),
        "`allowedFlagNames` for this leaf",
        &allowed,
    );

    // ownFlags(leaf) in foreign-flags.ts: the leaf's flags plus the globals.
    let own_names: Vec<String> = specs
        .iter()
        .map(|&index| flags[index].long.clone())
        .collect();
    let own_booleans: Vec<String> = specs
        .iter()
        .filter(|&&index| !flags[index].takes_value)
        .map(|&index| flags[index].long.clone())
        .collect();
    write_set(
        out,
        &format!("leaf_{ident}_own"),
        "Long names of `ownFlags(leaf)`",
        &own_names,
    );
    write_set(
        out,
        &format!("leaf_{ident}_own_boolean"),
        "Boolean long names of `ownFlags(leaf)`",
        &own_booleans,
    );

    // rewritesFor(leaf, own).
    let mode = leaf["foreignFlags"].as_str();
    let mut table: Vec<(String, String)> = Vec::new();
    if mode.is_some() {
        for (foreign, alias) in rewrites {
            if own_names.iter().any(|own| own == &foreign[2..]) {
                continue;
            }
            let replacement = match alias {
                None => Some(String::new()),
                Some(target) => {
                    let target_name = target[2..].split('=').next().unwrap();
                    let is_filter = mode == Some("update") && update_filters.contains(target);
                    if own_names.iter().any(|own| own == target_name) && !is_filter {
                        Some(target.clone())
                    } else if foreign.starts_with("--save-") {
                        Some(String::new())
                    } else {
                        None
                    }
                }
            };
            if let Some(replacement) = replacement {
                table.retain(|(existing, _)| existing != foreign);
                table.push((foreign.clone(), replacement));
            }
        }
    }
    writeln!(
        out,
        "fn leaf_{ident}_rewrite(token: &str) -> Option<&'static str> {{\n    match token {{"
    )
    .unwrap();
    for (foreign, replacement) in &table {
        writeln!(out, "        {foreign:?} => Some({replacement:?}),").unwrap();
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    let positionals: Vec<String> = leaf["positionals"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|positional| {
            format!(
                "PositionalDef {{ name: {:?}, required: {}, description: {:?} }}",
                str_of(&positional["name"]),
                positional["required"].as_bool().unwrap_or(false),
                str_of(&positional["description"])
            )
        })
        .collect();
    let foreign = match mode {
        Some("install") => "Some(ForeignMode::Install)",
        Some("update") => "Some(ForeignMode::Update)",
        None => "None",
        Some(other) => panic!("unknown foreignFlags mode {other}"),
    };
    assert!(
        leaf.get("passthrough").is_none(),
        "native leaf {name} must not be a passthrough leaf"
    );
    writeln!(
        out,
        "/// `fnpm {name}`.\npub static LEAF_{upper}: LeafDef = LeafDef {{\n    name: {name:?},\n    positionals: &[{}],\n    foreign: {foreign},\n    ignores_runtime_flags: {},\n    long: leaf_{ident}_long,\n    short: leaf_{ident}_short,\n    allowed: leaf_{ident}_allowed,\n    own: leaf_{ident}_own,\n    own_boolean: leaf_{ident}_own_boolean,\n    rewrite: leaf_{ident}_rewrite,\n}};\n",
        positionals.join(", "),
        leaf["ignoresRuntimeFlags"].as_bool().unwrap_or(false),
    )
    .unwrap();
}
